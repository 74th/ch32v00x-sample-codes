#!/usr/bin/env bash
# arduino-cli をリポジトリ内（.arduino/）に閉じて使うための入口。
# ホームの ~/.arduino15 や PATH 上の arduino-cli は使わない。
# 書き込み（upload）はこのスクリプトでは扱わない。書き込みは scripts/ch32fun.sh と ch32hil の固定 minichlink で行う。
set -euo pipefail
root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
base="$root/.arduino"
cli="$base/bin/arduino-cli"

# --- 固定値 ---------------------------------------------------------------
cli_version=1.5.1
case "$(uname -s)-$(uname -m)" in
  Linux-x86_64)
    cli_asset="arduino-cli_${cli_version}_Linux_64bit.tar.gz"
    cli_sha256=28a8e119c498a25607821c36cb2dc49e8463941b261a0d99091baa7bc692dd2b;;
  Linux-aarch64)
    cli_asset="arduino-cli_${cli_version}_Linux_ARM64.tar.gz"
    cli_sha256=1e69e077479f300614d4551334e0a33f08ee40b04315d83b8e7e0e94f0d0ee62;;
  *) cli_asset=""; cli_sha256="";;
esac
cli_url="https://github.com/arduino/arduino-cli/releases/download/v${cli_version}/${cli_asset}"

# 供給元ごとの board manager index と core のバージョン。
# thirdparty: 書籍 2.1 節の URL。official: openwch/arduino_core_ch32 README の URL。
# official-git: 参照用 clone externals/arduino_core_ch32 の固定 revision を export したもの（調査専用）。
thirdparty_url=https://raw.githubusercontent.com/robinjanssens/WCH32V_board_manager_files/main/package_ch32v_index.json
thirdparty_platform=WCH:ch32v@1.0.5-beta
official_url=https://github.com/openwch/board_manager_files/raw/main/package_ch32v_index.json
official_platform=WCH:ch32v@1.0.6
official_git_revision=d62c6b1646d7f139f1ac750ddfbd56120102ac5d
official_git_vendor=WCHgit   # 配布版 WCH:ch32v と名前が衝突しないよう vendor を変える
official_git_src="$root/externals/arduino_core_ch32"

usage() {
  cat >&2 <<EOF
usage:
  $0 setup                                   arduino-cli $cli_version を .arduino/bin/ に取得して照合する
  $0 config <supplier>                       .arduino/<supplier>/arduino-cli.yaml を生成する
  $0 core-install <supplier>                 固定バージョンの core を入れる（official-git は export）
  $0 cli <supplier> <args...>                固定設定で arduino-cli を実行する
  $0 compile <supplier> <sketch> <args...>   core list を表示してから arduino-cli compile する
  $0 fqbn <supplier> <board-id> [menu]       供給元の FQBN を表示する
supplier: thirdparty | official | official-git
EOF
  exit 2
}

need_cli() {
  if [[ ! -x "$cli" ]]; then
    echo "error: $cli がありません。先に '$0 setup' を実行してください" >&2; exit 1
  fi
  local v
  v="$("$cli" version --format json 2>/dev/null | sed -n 's/.*"VersionString": *"\([^"]*\)".*/\1/p')"
  if [[ "$v" != "$cli_version" ]]; then
    echo "error: $cli のバージョンが '$v' です（固定値 $cli_version）。'$0 setup' で取り直してください" >&2; exit 1
  fi
}

check_supplier() {
  case "${1:-}" in
    thirdparty|official|official-git) ;;
    *) echo "error: unknown supplier '${1:-}' (thirdparty | official | official-git)" >&2; exit 2;;
  esac
}

conf() { echo "$base/$1/arduino-cli.yaml"; }

write_config() {
  local s="$1" url data downloads user
  case "$s" in
    thirdparty) url="$thirdparty_url"; data="$base/thirdparty/data"; downloads="$base/thirdparty/downloads";;
    official) url="$official_url"; data="$base/official/data"; downloads="$base/official/downloads";;
    # ツールチェーンは official の data を共有する（core は user/hardware の export を使う）
    official-git) url="$official_url"; data="$base/official/data"; downloads="$base/official/downloads";;
  esac
  user="$base/$s/user"
  mkdir -p "$base/$s" "$data" "$downloads" "$user"
  cat > "$(conf "$s")" <<EOF
# generated by scripts/arduino.sh config $s
board_manager:
  additional_urls:
    - $url
directories:
  data: $data
  downloads: $downloads
  user: $user
build_cache:
  path: $base/$s/build-cache
updater:
  enable_notification: false
EOF
  echo "config: $(conf "$s")"
}

run_cli() {
  local s="$1"; shift
  [[ -f "$(conf "$s")" ]] || write_config "$s" >/dev/null
  "$cli" --config-file "$(conf "$s")" "$@"
}

platform_of() {
  case "$1" in
    thirdparty) echo "$thirdparty_platform";;
    official) echo "$official_platform";;
    official-git) echo "$official_git_vendor:ch32v@${official_git_revision:0:7}";;
  esac
}

case "${1:-}" in
  setup)
    [[ -n "$cli_asset" ]] || { echo "error: unsupported host $(uname -s)-$(uname -m)" >&2; exit 1; }
    mkdir -p "$base/bin" "$base/cache"
    archive="$base/cache/$cli_asset"
    if [[ ! -f "$archive" ]] || ! echo "$cli_sha256  $archive" | sha256sum -c --status; then
      curl -fsSL -o "$archive.part" "$cli_url"
      mv "$archive.part" "$archive"
    fi
    if ! echo "$cli_sha256  $archive" | sha256sum -c --status; then
      echo "SETUP FAILED: checksum mismatch for $archive (expected $cli_sha256)" >&2
      rm -f "$archive"; exit 1
    fi
    tar -xzf "$archive" -C "$base/bin" arduino-cli
    need_cli
    echo "arduino-cli: $cli ($("$cli" version))";;
  config)
    check_supplier "${2:-}"; write_config "$2";;
  core-install)
    check_supplier "${2:-}"; need_cli; s="$2"
    write_config "$s" >/dev/null
    case "$s" in
      thirdparty|official)
        run_cli "$s" core update-index
        run_cli "$s" core install "$(platform_of "$s")" --skip-post-install;;
      official-git)
        # ツールチェーンは official の core 導入で入る
        [[ -d "$base/official/data/packages/WCH/tools" ]] || "$0" core-install official
        actual="$(git -C "$official_git_src" rev-parse "$official_git_revision^{commit}" 2>/dev/null || true)"
        [[ "$actual" == "$official_git_revision" ]] || { echo "error: $official_git_src に $official_git_revision がありません" >&2; exit 1; }
        dest="$base/official-git/user/hardware/$official_git_vendor/ch32v"
        rm -rf "$dest"; mkdir -p "$dest"
        # 作業ツリーや index を変えずに、指定 revision の tree だけを書き出す
        git -C "$official_git_src" archive --format=tar "$official_git_revision" | tar -x -C "$dest"
        echo "$official_git_revision" > "$dest/.revision"
        echo "exported $official_git_revision to $dest";;
    esac
    run_cli "$s" core list;;
  cli)
    check_supplier "${2:-}"; need_cli; s="$2"; shift 2
    run_cli "$s" "$@";;
  compile)
    check_supplier "${2:-}"; [[ -n "${3:-}" ]] || usage; need_cli; s="$2"; sketch="$3"; shift 3
    echo "arduino-cli: $("$cli" version)"
    echo "supplier: $s (pinned $(platform_of "$s"))"
    if [[ "$s" == official-git ]]; then
      echo "official-git revision: $(cat "$base/official-git/user/hardware/$official_git_vendor/ch32v/.revision" 2>/dev/null || echo missing)"
    fi
    run_cli "$s" core list
    run_cli "$s" compile "$@" "$sketch";;
  fqbn)
    check_supplier "${2:-}"; [[ -n "${3:-}" ]] || usage
    vendor=WCH; [[ "$2" == official-git ]] && vendor="$official_git_vendor"
    echo "$vendor:ch32v:$3${4:+:$4}";;
  *) usage;;
esac
